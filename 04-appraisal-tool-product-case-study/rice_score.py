"""Score the backlog with RICE and turn it into a release plan.

RICE = (Reach x Impact x Confidence) / Effort
  Reach       people affected per quarter
  Impact      3 = massive, 2 = high, 1 = medium, 0.5 = low
  Confidence  0-1, how sure we are about reach and impact
  Effort      person-weeks

RICE ranks value per unit of effort. It doesn't handle dependencies, so the
release plan below adjusts the order where one item needs another first
(the appraiser workflow needs leads to exist before it's useful).
"""
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).parent
TEAM_WEEKS_PER_RELEASE = 8  # 4 developers x one 2-week sprint per release

backlog = pd.read_csv(ROOT / "rice_roadmap.csv")
backlog["rice"] = (backlog.reach_per_quarter * backlog.impact * backlog.confidence
                   / backlog.effort_person_weeks).round(0)
backlog = backlog.sort_values("rice", ascending=False).reset_index(drop=True)

# Dependencies: item -> items that must ship first
depends_on = {"US-02": ["US-01"], "US-03": ["US-01"], "US-04": ["US-03"],
              "US-05": ["US-04"], "US-06": ["US-05"], "US-07": ["US-02"]}

releases, shipped, remaining = [], set(), list(backlog.id)
while remaining:
    capacity, current = TEAM_WEEKS_PER_RELEASE, []
    while True:
        # Take the highest-RICE item that is ready (dependencies met) and fits.
        # Adding one item can unlock another, so rescan from the top each time.
        effort = backlog.set_index("id").effort_person_weeks
        pick = next((i for i in remaining
                     if all(d in shipped or d in current for d in depends_on.get(i, []))
                     and effort[i] <= capacity), None)
        if pick is None:
            break
        current.append(pick)
        capacity -= effort[pick]
        remaining.remove(pick)
    if not current:  # nothing fits: start a new release with the next item
        current.append(remaining.pop(0))
    shipped.update(current)
    releases.append(current)

backlog["release"] = backlog.id.map({i: n + 1 for n, r in enumerate(releases) for i in r})

print(backlog[["id", "item", "rice", "effort_person_weeks", "release"]].to_string(index=False))

lines = ["# Roadmap (generated by rice_score.py)", "",
         "| Release | ID | Item | RICE score | Effort (person-weeks) |", "|---|---|---|---|---|"]
for _, r in backlog.sort_values(["release", "rice"], ascending=[True, False]).iterrows():
    lines.append(f"| {r.release} | {r.id} | {r['item']} | {r.rice:,.0f} | {r.effort_person_weeks} |")
lines += ["", f"Capacity per release: {TEAM_WEEKS_PER_RELEASE} person-weeks. "
          "Items are taken in RICE order, but only once their dependencies have shipped."]
(ROOT / "roadmap.md").write_text("\n".join(lines) + "\n")
